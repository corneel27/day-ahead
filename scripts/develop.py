"""Set up and run isolated developer tools on Windows, Linux and macOS."""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
import threading
import time
import tomllib
import venv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TOOLS = ROOT / ".venv-tools"
PYTHON = TOOLS / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
RUFF = PYTHON.parent / ("ruff.exe" if os.name == "nt" else "ruff")
GUARD_HEADER = "# Generated by scripts/develop.py; do not edit.\n"
REMEDY = "Run 'Development: Set up Ruff', then 'Ruff: Restart Server' in VS Code."


def required_version() -> str:
    """Read the only maintained Ruff version pin."""
    matches = re.findall(
        r"^ruff==([0-9]+\.[0-9]+\.[0-9]+)\s*$",
        (ROOT / "requirements-lint.txt").read_text(encoding="utf-8"),
        flags=re.MULTILINE,
    )
    if len(matches) != 1:
        raise ValueError(
            "requirements-lint.txt must contain exactly one Ruff version pin."
        )
    return matches[0]


def write_version_guard() -> str:
    """Derive an ignored Ruff configuration, also protecting editor fallback."""
    pin = required_version()
    path = ROOT / ".ruff.toml"
    content = GUARD_HEADER + f'extend = "ruff.toml"\nrequired-version = "=={pin}"\n'
    # Windows can also deny a read briefly while another process replaces it.
    for attempt in range(20):
        try:
            previous = path.read_text(encoding="utf-8")
            break
        except FileNotFoundError:
            previous = ""
            break
        except PermissionError:
            if attempt == 19:
                raise
            time.sleep(0.05)
    if previous and not previous.startswith(GUARD_HEADER):
        raise ValueError(
            "An existing .ruff.toml is not generated; preserve it and resolve the configuration conflict."
        )
    if previous != content:
        # Workspace monitoring and editor starts can happen concurrently.
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            dir=ROOT,
            prefix=".ruff.toml-",
            suffix=".tmp",
            delete=False,
        ) as file:
            temporary = Path(file.name)
            file.write(content)
        try:
            for attempt in range(20):
                try:
                    temporary.replace(path)
                    break
                except PermissionError:
                    # Windows briefly denies replacement while another checker
                    # or the editor has the file open. Avoid spurious failures.
                    try:
                        if path.read_text(encoding="utf-8") == content:
                            break
                    except (FileNotFoundError, PermissionError):
                        pass
                    if attempt == 19:
                        raise
                    time.sleep(0.05)
        finally:
            temporary.unlink(missing_ok=True)
    return pin


def check_version(python: Path = PYTHON) -> str:
    pin = write_version_guard()
    if not python.is_file():
        raise ValueError(
            f"This checkout requires Ruff {pin}; developer tools are missing. {REMEDY}"
        )
    result = subprocess.run(
        [str(python), "-m", "ruff", "--version"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    installed = (
        result.stdout.strip().removeprefix("ruff ")
        if result.returncode == 0
        else "missing"
    )
    if installed != pin:
        raise ValueError(
            f"This checkout requires Ruff {pin}; installed version is {installed}. {REMEDY}"
        )
    launcher = TOOLS / ("ruff-project.exe" if os.name == "nt" else "ruff-project")
    if python == PYTHON and not launcher.is_file():
        raise ValueError(
            f"Ruff {pin} is installed but its version guard is missing. {REMEDY}"
        )
    return pin


def watch_versions() -> None:
    """Notify on checkout/tool changes without installing anything automatically."""
    previous = None
    last_state = None
    launcher = TOOLS / ("ruff-project.exe" if os.name == "nt" else "ruff-project")
    while True:
        try:
            state = (
                (ROOT / "requirements-lint.txt").read_bytes(),
                RUFF.stat().st_mtime_ns if RUFF.exists() else None,
                launcher.stat().st_mtime_ns if launcher.exists() else None,
            )
            if state == last_state:
                time.sleep(2)
                continue
            message = (
                f"Ruff {check_version()} is ready. You can start editing Python files. "
                "Next step: press F5 with 'Day Ahead: web preview' selected to open the application. "
                "This watcher stays running; you do not need to wait for it to finish."
            )
            last_state = state
        except (OSError, ValueError) as error:
            message = f"requirements-lint.txt:2:1: error: {error}"
            # Retry even when the pin and timestamps did not change: a lock or
            # interrupted replacement may have prevented the version check.
            last_state = None
        if message != previous:
            print("Ruff version check started", flush=True)
            print(message, flush=True)
            previous = message
        time.sleep(2)


def ruff_entry(arguments: list[str]) -> int:
    """Guard CLI/editor calls and stop a running server after a version change."""
    try:
        pin = check_version()
        with subprocess.Popen([str(RUFF), *arguments], cwd=ROOT) as process:
            stopped = threading.Event()

            def monitor():
                while not stopped.wait(1):
                    try:
                        if required_version() == pin:
                            continue
                        message = f"Ruff server version {pin} no longer matches this checkout. {REMEDY}"
                    except (OSError, ValueError) as error:
                        message = str(error)
                    print(message, file=sys.stderr, flush=True)
                    process.terminate()
                    return

            if "server" in arguments:
                threading.Thread(target=monitor, daemon=True).start()
            try:
                return process.wait()
            finally:
                stopped.set()
    except (OSError, ValueError) as error:
        print(f"Developer tools: {error}", file=sys.stderr, flush=True)
        return 1


def run(*args: str) -> None:
    """Run an argument list without a shell and preserve tool failure codes."""
    subprocess.run(args, cwd=ROOT, check=True)


def setup() -> None:
    """Install pinned tools without changing the application environment."""
    target = tomllib.loads((ROOT / "ruff.toml").read_text())["target-version"]
    minimum = (int(target[2]), int(target[3:]))
    if sys.version_info[:2] < minimum:
        raise ValueError(f"Use Python {minimum[0]}.{minimum[1]} or newer for setup.")
    hooks_path = subprocess.run(
        ["git", "config", "--get", "core.hooksPath"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    if hooks_path.returncode not in (0, 1):
        raise ValueError("Cannot read Git hook settings. Is Git installed?")
    if hooks_path.returncode == 0:
        raise ValueError(
            "core.hooksPath is configured. Integrate pre-commit with your existing "
            "hook setup before continuing; this script will not change that setting."
        )
    if TOOLS.exists() and not (TOOLS / "pyvenv.cfg").is_file():
        raise ValueError(
            ".venv-tools exists but is not a virtual environment; leave it intact."
        )
    if not PYTHON.is_file():
        venv.EnvBuilder(with_pip=True).create(TOOLS)
    run(str(PYTHON), "-m", "pip", "install", "-r", "requirements-dev.txt")
    # Build away from the source tree; pip produces portable console launchers.
    with tempfile.TemporaryDirectory(dir=TOOLS) as directory:
        package = Path(directory) / "ruff_guard"
        shutil.copytree(ROOT / "tools/ruff_guard", package)
        run(str(PYTHON), "-m", "pip", "install", "--no-deps", str(package))
    launcher = PYTHON.parent / (
        "ruff-project.exe" if os.name == "nt" else "ruff-project"
    )
    shutil.copy2(launcher, TOOLS / launcher.name)
    # pre-commit requires the literal entry path to exist on Windows too.
    if os.name == "nt":
        shutil.copy2(launcher, TOOLS / "ruff-project")
    check_version()
    run(str(PYTHON), "-m", "pre_commit", "validate-config")
    # Install environments up front so the first commit does not need downloads.
    # pre-commit's default migration mode preserves an existing custom hook.
    run(str(PYTHON), "-m", "pre_commit", "install", "--install-hooks")
    run(str(PYTHON), "-m", "ruff", "--version")
    run(str(PYTHON), "-m", "ruff", "check", ".")
    print("Setup complete. Ruff is ready.", flush=True)
    print(
        "If Ruff was already running before setup, run 'Ruff: Restart Server' in VS Code. "
        "A fresh Dev Container starts Ruff automatically after setup.",
        flush=True,
    )
    print("Safe lint fixes run on save. Review fixes before committing.", flush=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "action",
        choices=("setup", "check", "fix", "hooks", "status", "watch", "ci-check"),
    )
    action = parser.parse_args().action
    try:
        if action == "setup":
            setup()
        elif action == "watch":
            watch_versions()
        elif action == "ci-check":
            check_version(Path(sys.executable))
            run(sys.executable, "-m", "ruff", "check", "--output-format", "github", ".")
        else:
            pin = check_version()
            if action == "status":
                print(f"Ruff {pin} matches requirements-lint.txt.")
                return 0
            if action == "hooks":
                run(str(PYTHON), "-m", "pre_commit", "run", "--all-files")
            else:
                args = [str(PYTHON), "-m", "ruff", "check"]
                if action == "fix":
                    args.append("--fix")
                run(*args, ".")
    except KeyboardInterrupt:
        return 0
    except subprocess.CalledProcessError as error:
        return error.returncode
    except (OSError, ValueError) as error:
        print(f"Developer tools: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
